/* ─────────────────────────────────────────────────────────────
   Generates src/reader/pdfWidths.ts — the glyph advance widths the marks
   PDF exporter needs to break a line.

   The widths are Adobe's own, for five of the base-14 fonts, lifted out of
   pdfjs-dist's metrics table (build/pdf.worker.mjs, `getMetrics`) rather than
   typed in from memory. pdfjs is already a dependency of this app for the PDF
   reader, so no new one is added and nothing is guessed.

   Base-14 means the PDF embeds no font program at all: the file is a few KB,
   the export needs no network, and every PDF reader in the world already has
   these five faces. The cost is that only WinAnsi (cp1252) can be encoded —
   see toWinAnsi() in pdfExport.ts for what happens to a character outside it.

   Run:  node scripts/make-pdf-widths.mjs
   ───────────────────────────────────────────────────────────── */
import { readFileSync, writeFileSync } from 'node:fs'

const SRC = 'node_modules/pdfjs-dist/build/pdf.worker.mjs'
const src = readFileSync(SRC, 'utf8')

/* WinAnsiEncoding, code → glyph name. pdfjs prints it as one array literal. */
const encLine = src.match(/^const WinAnsiEncoding = (\[.*\]);$/m)
if (!encLine) throw new Error('WinAnsiEncoding not found in ' + SRC)
const WINANSI = JSON.parse(encLine[1])

/** The body of `t["<name>"] = getLookupTableFactory(function (t) { … });` */
function metricsFor(font) {
  const key = /^[A-Za-z]+$/.test(font) ? `t.${font}` : `t["${font}"]`
  const at = src.indexOf(`  ${key} = getLookupTableFactory(function (t) {`)
  if (at < 0) throw new Error('no metrics block for ' + font)
  const end = src.indexOf('\n  });', at)
  const body = src.slice(at, end)
  const table = Object.create(null)
  for (const m of body.matchAll(/\n    t(?:\.([A-Za-z0-9_]+)|\["([^"]+)"\]) = (-?\d+);/g))
    table[m[1] ?? m[2]] = Number(m[3])
  return table
}

const FONTS = ['Times-Roman', 'Times-Bold', 'Times-Italic', 'Helvetica', 'Helvetica-Bold']

const out = []
out.push('/* GENERATED by scripts/make-pdf-widths.mjs — do not edit by hand.')
out.push('   Adobe base-14 advance widths, 1/1000 em, indexed by WinAnsi code point')
out.push('   0–255. Source: pdfjs-dist\'s own `getMetrics` table. A code with no glyph')
out.push('   in the encoding is 0 and is never emitted — pdfExport.ts substitutes')
out.push('   before it measures. */')
out.push('')
for (const font of FONTS) {
  const t = metricsFor(font)
  const row = []
  for (let c = 0; c < 256; c++) {
    const g = WINANSI[c]
    row.push(g && t[g] != null ? t[g] : 0)
  }
  const name = 'W_' + font.replace(/-/g, '_').toUpperCase()
  const lines = []
  for (let i = 0; i < 256; i += 16) lines.push('    ' + row.slice(i, i + 16).join(','))
  out.push(`export const ${name}: readonly number[] = [`)
  out.push(lines.join(',\n'))
  out.push(']')
  out.push('')
  const covered = row.filter(w => w > 0).length
  console.log(`${font.padEnd(16)} ${covered}/224 encodable codes measured`)
}
writeFileSync('src/reader/pdfWidths.ts', out.join('\n'))
console.log('wrote src/reader/pdfWidths.ts')
